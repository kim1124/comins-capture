import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {resolve} from 'node:path';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const topics = [
  ['01-quick-start', 'getting-started', 'Quick Start', '빠른 시작'],
  ['02-core-concepts', 'architecture', 'Core Concepts', '핵심 개념'],
  ['03-frameworks', 'frameworks', 'Framework Integration', '프레임워크 연동'],
  ['04-output-options', 'output-options', 'Output Options', '출력 옵션'],
  ['05-resources', 'dom-integration', 'Input and Resources', '입력과 자원'],
  ['06-lifecycle-errors', 'troubleshooting', 'Lifecycle and Errors', '수명주기와 오류'],
  ['07-playground', 'playground', 'Playground', 'Playground'],
  ['08-browser-support', 'support', 'Browser Support', '지원과 검증'],
  ['09-public-api', 'api', 'Public API Reference', '공개 API'],
  ['10-site-integration', 'site-integration', 'Site Integration', '사이트 연동'],
];
const mapped = new Map(topics.map(([name, source]) => [`${source}.md`, `${name}.md`]));
mapped.set('README.md', '../README.md');

// 국문 참조 문서는 구현 계약 원본에서 생성해 별도 복사본의 수정을 방지한다.
export async function koreanReference([name, source]) {
  const input = await readFile(resolve(root, `docs/guide/${source}.md`), 'utf8');
  const body = input.replace(/(\[[^\]]*\]\()([^)]+)(\))/g, (all, start, target, end) => {
    const [file, anchor] = target.split('#');
    const replacement = mapped.get(file);
    return replacement ? `${start}${replacement}${anchor ? `#${anchor}` : ''}${end}` : all;
  });
  const navigation = `[English](../user/${name}.md) · [문서 목차](../README.md) · [구현 계약 원본](../guide/${source}.md)`;
  return `<!-- Generated by scripts/reference-docs.mjs. Edit docs/guide/${source}.md. -->\n\n${navigation}\n\n${body}`;
}

export async function referenceDocs(write = false) {
  if (write) await mkdir(resolve(root, 'docs/ko'), {recursive:true});
  for (const topic of topics) {
    const path = resolve(root, `docs/ko/${topic[0]}.md`);
    const expected = await koreanReference(topic);
    if (write) await writeFile(path, expected);
    else if (await readFile(path, 'utf8') !== expected) throw new Error('REFERENCE_DOCS_OUT_OF_SYNC');
    await readFile(resolve(root, `docs/user/${topic[0]}.md`), 'utf8');
  }
  return topics.length;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const count = await referenceDocs(process.argv.includes('--write'));
  console.log(`reference-docs: ${count} language pairs ${process.argv.includes('--write') ? 'generated' : 'checked'}`);
}
